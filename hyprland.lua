hl.config({ autogenerated = false })


-- ##################################################################
-- ### STARTUP
-- ##################################################################

-- Run once when Hyprland starts.
hl.on("hyprland.start", function()
    -- Share the session environment with D-Bus and user services.
    hl.exec_cmd("dbus-update-activation-environment --systemd --all")

    -- Start services attached to the Hyprland session.
    hl.exec_cmd("systemctl --user start hyprland-session.target")

    -- Launch Kitty on the hidden dropdown workspace.
    hl.exec_cmd("kitty --class kitty-dropdown --title kitty-dropdown", {
        workspace = "special:dropdown silent",
    })
end)


